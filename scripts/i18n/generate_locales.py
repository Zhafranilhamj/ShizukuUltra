#!/usr/bin/env python3
"""Generate the locale list Android needs, replacing the AutoResConfig Gradle plugin.

Why this exists: AutoResConfig (dev.rikka.tools.autoresconfig) resolves AGP's legacy
`AppExtension`, which AGP 9 removed, so applying it throws
`GradleException: Android application extension not found` and the manager module cannot be
configured or built at all. Its last release is v1.2.1 (2022). The plugin did three small things
for manager/build.gradle's `autoResConfig { ... }` block, all reproduced here:

  1. generatedClassFullName = "af.shizuku.manager.ShizukuLocales"
       A Java class with LOCALES[] and DISPLAY_LOCALES[], each prefixed with generatedArrayFirstItem
       ("SYSTEM"), listing every BCP-47 language tag that has a values-<tag> directory with a
       non-empty strings.xml. PersonalizationSettingsFragment.kt builds the in-app language picker
       from those two arrays, so the prefix and the order matter.
  2. generateLocaleConfig = true
       res/xml/locales_config.xml, referenced by android:localeConfig in the manifest, listing the
       same tags for Android 13's per-app language settings.
  3. (implicitly) resourceConfigurations, which `aapt2 optimize --collapse-resource-names` and the
       resource shrinker already narrow down here, so it is not reproduced.

Usage:  python3 scripts/i18n/generate_locales.py          # write the files
        python3 scripts/i18n/generate_locales.py --check  # exit 1 if they are out of date

Keep this script and the generated files in sync: CI runs --check.
"""
import glob
import os
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, "manager", "src", "main", "res")
JAVA_OUT = os.path.join(ROOT, "manager", "src", "main", "java", "af", "shizuku", "manager",
                        "ShizukuLocales.java")
XML_OUT = os.path.join(RES, "xml", "locales_config.xml")

# Mirrors autoResConfig { generatedArrayFirstItem = "SYSTEM" }. The picker treats this entry as
# "follow the system language", so it must be first in both arrays.
FIRST_ITEM = "SYSTEM"


def locale_tag(dirname):
    """values-pt-rBR -> pt-BR, values-zh-rCN -> zh-CN, values-b+sr+Latn -> sr-Latn, values-de -> de.

    Mirrors AutoResConfig's convertModifiersToLocales; anything with more than three '-' segments
    was skipped there too (e.g. values-v27 is a version qualifier, not a locale).
    """
    modifier = dirname[len("values-"):]
    if len(modifier.split("-")) > 3:
        return None
    if modifier.startswith("b+"):
        parts = modifier[len("b+"):].split("+", 1)
        return parts[0] if len(parts) == 1 else f"{parts[0]}-{parts[1]}"
    parts = modifier.split("-", 1)
    if len(parts) == 1:
        return parts[0]
    region = parts[1]
    if not region.startswith("r") or len(region) < 2:
        return None
    return f"{parts[0]}-{region[1:]}"


def collect():
    tags = {"en"}  # AutoResConfig always adds en
    for d in sorted(glob.glob(os.path.join(RES, "values-*"))):
        if not os.path.isdir(d):
            continue
        strings = os.path.join(d, "strings.xml")
        # AutoResConfig skipped empty strings.xml files; keep that rule so a locale that only
        # carries arrays or themes doesn't show up in the picker.
        if not os.path.isfile(strings) or os.path.getsize(strings) <= 62:
            continue
        tag = locale_tag(os.path.basename(d))
        if tag:
            tags.add(tag)
    return sorted(tags, key=str.casefold)


def java_source(tags):
    lines = [
        "package af.shizuku.manager;",
        "",
        "/**",
        " * Language tags the UI can switch to, generated by scripts/i18n/generate_locales.py from the",
        " * values-&lt;tag&gt; resource directories. Do not edit by hand: re-run the script (CI checks",
        " * that this file matches the resources).",
        " *",
        " * The first entry is \"" + FIRST_ITEM + "\": the in-app picker maps it to \"follow the system\".",
        " * AutoResConfig generated this class before it stopped working with AGP 9.",
        " */",
        "public final class ShizukuLocales {",
        "    private ShizukuLocales() {}",
        "",
        "    public static final String[] LOCALES = {",
    ]
    lines += [f'            "{t}",' for t in tags]
    lines += ["    };", "", "    public static final String[] DISPLAY_LOCALES = {", f'            "{FIRST_ITEM}",']
    lines += [f'            "{t}",' for t in tags]
    lines += ["    };", "}", ""]
    return "\n".join(lines)


def xml_source(tags):
    body = "\n".join(f'    <locale android:name="{t}"/>' for t in tags)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/i18n/generate_locales.py from the values-<tag> directories.\n"
        "     Referenced by android:localeConfig in AndroidManifest.xml so Android 13's per-app\n"
        "     language screen lists the same languages the in-app picker does. Do not edit. -->\n"
        '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f"{body}\n"
        "</locale-config>\n"
    )


def main():
    tags = collect()
    if not tags:
        print("generate_locales: no locale directories found", file=sys.stderr)
        return 1
    outputs = {JAVA_OUT: java_source(tags), XML_OUT: xml_source(tags)}
    check_only = "--check" in sys.argv[1:]
    stale = []
    for path, content in outputs.items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != content:
            stale.append(path)
            if not check_only:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8") as f:
                    f.write(content)
    if check_only:
        if stale:
            for p in stale:
                print(f"out of date: {os.path.relpath(p, ROOT)}", file=sys.stderr)
            print("run: python3 scripts/i18n/generate_locales.py", file=sys.stderr)
            return 1
        print(f"locales OK ({len(tags)} tags)")
        return 0
    for p in stale:
        print(f"wrote {os.path.relpath(p, ROOT)}")
    print(f"{len(tags)} locales: {', '.join(tags)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
