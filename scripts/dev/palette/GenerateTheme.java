    /** palette* attributes for the dynamic themes, mapped onto the platform's system accents. */
    private void paletteSystemTokens() {
        String[] palettes = {"Primary", "Secondary", "Tertiary"};
        for (int i = 0; i < palettes.length; i++) {
            String accent = "system_accent" + (i + 1);
            // Android's system accent tones run 0 (darkest) .. 1000; Material's tone scale is the
            // reverse, which is why 100 maps to _0 and 0 maps to _1000.
            int[] platform = {0, 10, 50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000};
            for (int t = 0; t < TONES.length; t++) {
                ref(String.format("palette%s%d", palettes[i], TONES[t]), "@android:color/" + accent + "_" + platform[t]);
            }
        }
        // Neutral roles come from the platform's neutral accents.
        int[] platform = {0, 10, 50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000};
        for (int t = 0; t < TONES.length; t++) {
            ref(String.format("paletteNeutral%d", TONES[t]), "@android:color/system_neutral1_" + platform[t]);
            ref(String.format("paletteNeutralVariant%d", TONES[t]), "@android:color/system_neutral2_" + platform[t]);
            ref(String.format("paletteError%d", TONES[t]), "@android:color/system_error_" + platform[t]);
        }
    }

    // ---------------------------------------------------------------- helpers

    private void color(int argb, String theme, String mode, String role) {
        out.append(String.format("    <color name=\"%s\">%s</color>\n", md(theme, mode, role), hex(argb)));
    }

    private static String md(String theme, String mode, String role) {
        return mode == null
                ? String.format("md_theme_%s_%s", theme, role)
                : String.format("md_theme_%s_%s_%s", theme, mode, role);
    }

    private static String md(String theme, String role) {
        return md(theme, null, role);
    }

    /**
     * Writes <item> for the given attribute. Values that already are a reference (@color/... or
     * @android:color/...) are written as-is; bare names are treated as this project's @color/ entries.
     */
    private void ref(String name, String value) {
        String v = value.startsWith("@") ? value : "@color/" + value;
        out.append("    <item name=\"").append(name).append("\">").append(v).append("</item>\n");
    }

    private void attr(String name, String format) {
        out.append(String.format("    <attr name=\"%s\" format=\"%s\" />\n", name, format));
    }

    private void declareStyleable(String name) {
        out.append(String.format("    <declare-styleable name=\"%s\">\n", name));
    }

    private void endDeclareStyleable() {
        out.append("    </declare-styleable>\n");
    }

    private static String hex(int argb) {
        return String.format(Locale.ROOT, "#%06X", argb & 0xFFFFFF);
    }

    private static String capitalizeSnake(String name) {
        StringBuilder sb = new StringBuilder();
        for (String part : name.split("_")) {
            if (part.isEmpty()) {
                continue;
            }
            sb.append(Character.toUpperCase(part.charAt(0))).append(part.substring(1));
        }
        return sb.toString();
    }
