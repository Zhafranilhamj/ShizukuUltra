    private void paletteRef(String paletteAttr, int tone, String themeName) {
        String palette = paletteAttr.toLowerCase(Locale.ROOT).replace("variant", "_variant");
        ref(String.format("palette%s%d", paletteAttr, tone),
                String.format("md_theme_%s_palette_%s_%d", themeName, palette, tone));
    }

